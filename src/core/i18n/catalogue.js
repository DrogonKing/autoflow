/**
 * The message catalogue, and why it is a plain object rather than chrome.i18n.
 *
 * `chrome.i18n` is the platform way, and it was rejected for three measured reasons:
 *
 *   1. It resolves the locale ONCE, at load, from the browser's UI language. There is no supported way to
 *      override it per user, so a Persian speaker on an English Chrome would get English with no recourse -
 *      and the request here was explicitly "make the panel Persian".
 *   2. It cannot be switched at runtime without reloading every page of the extension.
 *   3. This project already has a settings store and a platform layer; a 20-line lookup is less machinery
 *      than a second localisation mechanism running in parallel.
 *
 * The tests assert that every key used in the UI exists in BOTH catalogues, and that the Persian catalogue
 * has no key the English one lacks. A half-translated panel is worse to read than a fully English one, so the
 * coverage check is a test rather than a promise.
 */

